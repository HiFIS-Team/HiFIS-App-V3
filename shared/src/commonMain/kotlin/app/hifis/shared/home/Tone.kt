package app.hifis.shared.home

/**
 * 색을 고르는 기준 — **색 이름이 아니라 뜻**이다
 *
 * 두 플랫폼이 각자 `when` 으로 상태를 색에 잇게 두면 언젠가 갈린다.
 * 뜻을 여기서 정하고, 색은 각 플랫폼의 토큰에서 **한 번만** 잇는다.
 *
 * 처음에는 근무 상태 전용(`WorkTone`)이었는데 홈 알림도 같은 뜻을 쓰게 돼 옮겼다.
 */
enum class Tone {
    /** 아직 아무 일도 없다 — 미출근·휴무·판정 불가 */
    NEUTRAL,

    /** 잘 됐다 — 출근 중·승인됨 */
    GOOD,

    /** 짚어 볼 것 — 지각·조기 퇴근·마감 임박 */
    CAUTION,

    /** 문제 — 결근·퇴근 누락·반려됨 */
    BAD,

    /** 알림 — 휴가·남은 할 일 */
    INFO,
}
